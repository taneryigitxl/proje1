import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import net from 'node:net';
import pg from 'pg';
import WebSocket from 'ws';
import EmbeddedPostgres from 'embedded-postgres';
import { migrate } from '../server/migrate.js';
import { createApp } from '../server/app.js';
import { CLIENT, SERVER, PROTOCOL_VERSION } from '../shared/Protocol.js';

const freePort = () => new Promise((resolve, reject) => {
  const server = net.createServer();
  server.once('error', reject);
  server.listen(0, '127.0.0.1', () => { const port = server.address().port; server.close(() => resolve(port)); });
});
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));

test('gerçek PostgreSQL ve iki WebSocket istemcisi ortak dünya/veri tutarlılığı', { timeout: 180_000 }, async () => {
  const dir = await mkdtemp(path.join(tmpdir(), 'tora-online-pg-'));
  const dbPort = await freePort();
  const embedded = new EmbeddedPostgres({ databaseDir: path.join(dir, 'db'), user: 'postgres', password: 'test-password', port: dbPort, persistent: false, initdbFlags: ['--locale=C', '--encoding=UTF8'], onLog: () => {}, onError: () => {} });
  let pool, app, a, b;
  try {
    await embedded.initialise();
    await embedded.start();
    await embedded.createDatabase('tora_test');
    pool = new pg.Pool({ connectionString: `postgres://postgres:test-password@127.0.0.1:${dbPort}/tora_test` });
    await migrate(pool);
    const config = { databaseUrl: 'test', origins: ['http://localhost:5173'], port: 0, production: false, cookieName: 'tora_session', sessionDays: 7 };
    app = await createApp({ config, pool });
    const { port } = await app.listen(0);
    const base = `http://127.0.0.1:${port}`;
    const api = async (route, method = 'GET', body, cookie) => {
      const response = await fetch(base + route, { method, headers: { Origin: 'http://localhost:5173', ...(body ? { 'Content-Type': 'application/json' } : {}), ...(cookie ? { Cookie: cookie } : {}) }, body: body ? JSON.stringify(body) : undefined });
      return { status: response.status, data: await response.json(), cookie: response.headers.get('set-cookie')?.split(';')[0] };
    };
    const createUser = async suffix => {
      assert.equal((await api('/auth/register', 'POST', { username: `User${suffix}`, email: `${suffix}@example.com`, password: 'passphrase-123456' })).status, 201);
      const logged = await api('/auth/login', 'POST', { login: `User${suffix}`, password: 'passphrase-123456' });
      assert.equal(logged.status, 200);
      assert.ok(logged.cookie?.startsWith('tora_session='));
      const created = await api('/characters', 'POST', { name: `Hero${suffix}`, classId: 'warrior' }, logged.cookie);
      assert.equal(created.status, 201);
      return { cookie: logged.cookie, id: created.data.character.id };
    };
    const userA = await createUser('Alpha'), userB = await createUser('Beta');
    assert.equal((await api('/characters', 'GET', null, userA.cookie)).data.characters.length, 1);
    assert.equal((await api('/characters', 'GET', null, userB.cookie)).data.characters.length, 1);
    const forbidden = await api('/characters', 'GET');
    assert.equal(forbidden.status, 401);
    await pool.query("UPDATE characters SET region_id='forest',position_x=0,position_z=-17 WHERE id=ANY($1::uuid[])", [[userA.id, userB.id]]);
    const connect = async user => {
      const ws = new WebSocket(`ws://127.0.0.1:${port}/game?v=${PROTOCOL_VERSION}&characterId=${user.id}`, { headers: { Origin: 'http://localhost:5173', Cookie: user.cookie } });
      const packets = [];
      ws.on('message', raw => packets.push(JSON.parse(raw.toString())));
      await new Promise((resolve, reject) => { ws.once('open', resolve); ws.once('error', reject); });
      return { ws, packets, seq: 0, send(type, fields = {}) { ws.send(JSON.stringify({ type, seq: ++this.seq, ...fields })); } };
    };
    const until = async (client, predicate, timeout = 5000) => {
      const end = Date.now() + timeout;
      while (Date.now() < end) { const packet = client.packets.find(predicate); if (packet) return packet; await delay(20); }
      throw Error('Packet timeout: ' + client.packets.map(p => p.type).join(', '));
    };
    a = await connect(userA); b = await connect(userB);
    assert.equal((await until(a, p => p.type === SERVER.WELCOME)).authoritative, true);
    assert.equal((await until(b, p => p.type === SERVER.WELCOME)).characterId, userB.id);
    await until(a, p => p.type === SERVER.SNAPSHOT && p.players.some(x => x.id === userB.id));
    await until(b, p => p.type === SERVER.SNAPSHOT && p.players.some(x => x.id === userA.id));
    const first = await until(a, p => p.type === SERVER.SNAPSHOT && p.mobs.length > 0);
    assert.deepEqual(first.mobs.map(x => x.id), (await until(b, p => p.type === SERVER.SNAPSHOT && p.mobs.length > 0)).mobs.map(x => x.id));
    const xBefore = app.world.players.get(userA.id).x;
    a.send(CLIENT.MOVE, { dx: 1, dz: 0, x: 99999, gold: 99999 });
    await delay(350);
    a.send(CLIENT.MOVE, { dx: 0, dz: 0 });
    const moved = app.world.players.get(userA.id).x;
    assert.ok(moved > xBefore && moved - xBefore < 2, 'server hesaplı hız');
    assert.equal(app.world.players.get(userA.id).gold, 50, 'istemci altın belirleyemez');
    await until(b, p => p.type === SERVER.SNAPSHOT && p.players.some(x => x.id === userA.id && x.x > xBefore));
    const target = app.world.room('forest').mobs[0];
    const startingGold = app.world.players.get(userA.id).gold;
    app.world.players.get(userA.id).x = target.x + 2;
    app.world.players.get(userA.id).z = target.z;
    target.health = 1;
    a.send(CLIENT.ATTACK, { targetId: target.id, damage: 999999, xp: 999999 });
    await until(a, p => p.type === SERVER.COMBAT && p.phase === 'impact' && p.targetId === target.id && p.dead, 5000);
    await until(a, p => p.type === SERVER.PROGRESSION && p.earnedGold > 0, 5000);
    await until(b, p => p.type === SERVER.SNAPSHOT && p.mobs.some(m => m.id === target.id && !m.alive), 5000);
    const loot = await until(a, p => p.type === SERVER.LOOT && p.loot?.ownerId === userA.id);
    a.send(CLIENT.PICKUP, { lootId: loot.loot.id, itemId: 'iron-blade', quantity: 999 });
    await until(a, p => p.type === SERVER.INVENTORY && p.items.length === 6);
    const inventory = await pool.query('SELECT item_id,quantity FROM inventory_items WHERE character_id=$1 ORDER BY slot', [userA.id]);
    assert.equal(inventory.rows.length, 6);
    assert.equal(inventory.rows.at(-1).item_id, loot.loot.itemId);
    assert.equal(inventory.rows.at(-1).quantity, 1, 'istemci miktar belirleyemez');
    const potion = (await pool.query("SELECT id FROM inventory_items WHERE character_id=$1 AND item_id='health-potion' ORDER BY slot DESC LIMIT 1", [userA.id])).rows[0];
    const playerA = app.world.players.get(userA.id); playerA.health -= 45;
    a.send(CLIENT.USE, { itemId: potion.id, health: 99999 });
    await until(a, p => p.type === SERVER.INVENTORY && p.items.length === 5);
    assert.ok(playerA.health <= playerA.maxHealth && playerA.health > playerA.maxHealth - 45);
    assert.equal((await pool.query('SELECT 1 FROM inventory_items WHERE id=$1', [potion.id])).rowCount, 0);
    assert.ok(app.world.players.get(userA.id).gold > startingGold, 'sunucu öldürme ödülünü hesapladı');
    const rewarded = await pool.query('SELECT gold,xp FROM characters WHERE id=$1', [userA.id]);
    assert.equal(rewarded.rows[0].gold, app.world.players.get(userA.id).gold);
    assert.ok(rewarded.rows[0].xp > 0);
    a.ws.close();
    await delay(250);
    const saved = await pool.query('SELECT position_x,gold FROM characters WHERE id=$1', [userA.id]);
    assert.ok(saved.rows[0].position_x > xBefore);
    assert.equal(saved.rows[0].gold, rewarded.rows[0].gold);
    a = await connect(userA);
    const restored = await until(a, p => p.type === SERVER.SNAPSHOT && p.inventory);
    assert.equal(restored.self.x, saved.rows[0].position_x);
    assert.equal(restored.inventory.gold, rewarded.rows[0].gold);
    assert.equal(restored.inventory.items.length, 5);
    const rejoined = app.world.players.get(userA.id);
    rejoined.x = 0; rejoined.z = -20;
    a.send(CLIENT.PORTAL, { portalId: 'village', region: 'ruins' });
    await until(a, p => p.type === SERVER.REGION && p.region === 'village');
    assert.equal(rejoined.region, 'village');
    rejoined.x = -2; rejoined.z = 2;
    a.send(CLIENT.INTERACT, { action: 'npc:buy:health-potion', gold: 99999 });
    await until(a, p => p.type === SERVER.INVENTORY && p.items.length === 6);
    assert.equal(rejoined.gold, rewarded.rows[0].gold - 12);
    await delay(240);
    rejoined.x = 11; rejoined.z = -8;
    a.send(CLIENT.INTERACT, { action: 'chest:chest' });
    await until(a, p => p.type === SERVER.INVENTORY && p.items.length === 7);
    assert.equal((await pool.query("SELECT count(*)::int AS count FROM character_chests WHERE character_id=$1 AND chest_id='chest'", [userA.id])).rows[0].count, 1);
    await delay(240);
    a.send(CLIENT.INTERACT, { action: 'chest:chest' });
    await until(a, p => p.type === SERVER.ERROR && /zaten açılmış/.test(p.message));
    assert.equal((await pool.query('SELECT count(*)::int AS count FROM inventory_items WHERE character_id=$1', [userA.id])).rows[0].count, 7);
    a.ws.close(); b.ws.close();
  } finally {
    a?.ws.terminate(); b?.ws.terminate();
    if (app) await app.close(); else await pool?.end();
    await embedded.stop().catch(() => {});
    await rm(dir, { recursive: true, force: true });
  }
});
